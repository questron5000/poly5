"""Write firmware/gen/poly5_tables.h: the constants POLY5's engine needs (the chip has no FPU, so they are
computed here). Run it again after a change: python3 tools/gen_poly5_tables.py"""
import math
from pathlib import Path

FS = 44100.0
BLK = 16                      # frames per control block (envelopes, filter coefficients)
BR = FS / BLK                 # control blocks per second

out = []
w = out.append
w("/* SPDX-License-Identifier: GPL-3.0-only */")
w("/* Generated by tools/gen_poly5_tables.py: do not edit. */")
w("#ifndef POLY5_TABLES_H")
w("#define POLY5_TABLES_H")
w(f"#define P5_BLK {BLK}u")

# SVF g = tan(pi fc / fs), Q12, over fc = 20 Hz * 2^(i/64), i = 0..640 (10 octaves); clamped at 20 kHz
g = []
for i in range(641):
    fc = min(20.0 * 2 ** (i / 64.0), 20000.0)
    g.append(round(math.tan(math.pi * fc / FS) * 4096))
w("/* g = tan(pi fc / 44100) in Q12, fc = 20 Hz * 2^(i/64), clamped at 20 kHz */")
w("static const uint16_t P5_GTAB[641] = {" + ",".join(map(str, g)) + "};")

# k = 1 / Q, Q = 10^(dB/20), dB = reso * 0.5 (Web Audio's lowpass Q is in dB), Q12, reso 0..30
k = [round(4096 / 10 ** (r * 0.5 / 20)) for r in range(31)]
w("/* k = 1/Q in Q12 for reso 0..30 (Poly5: Q = reso * 0.5 dB) */")
w("static const uint16_t P5_KTAB[31] = {" + ",".join(map(str, k)) + "};")

# log2(1 + x), x = i/256 (0..1), Q12
l = [round(math.log2(1 + i / 256.0) * 4096) for i in range(257)]
w("/* log2(1 + i/256) in Q12 */")
w("static const uint16_t P5_LOG2_1PX[257] = {" + ",".join(map(str, l)) + "};")

# 2^(i/256), i = 0..256, Q15 (fractional part of exp2)
e = [round(2 ** (i / 256.0) * 32768) for i in range(257)]
w("/* 2^(i/256) in Q15 */")
w("static const uint32_t P5_EXP2[257] = {" + ",".join(map(str, e)) + "};")

# decay factors per block: the VCA to 0.7, the filter envelope to 0.4, both over 80 ms (Poly5's exponential ramps)
nb = 0.08 * BR
w(f"#define P5_DEC_BLOCKS {round(nb)}u")
w(f"#define P5_DEC_VCA_Q30 {round(0.7 ** (1 / nb) * (1 << 30))}u   /* 0.7^(1/blocks) */")
w(f"#define P5_DEC_FLT_Q30 {round(0.4 ** (1 / nb) * (1 << 30))}u   /* 0.4^(1/blocks) */")
w(f"#define P5_SUS_VCA_Q24 {round(0.7 * (1 << 24))}u")
w(f"#define P5_SUS_FLT_Q24 {round(0.4 * (1 << 24))}u")
# the release ends at 0.0001 (Web Audio exponentialRamp target): log2(1e-4) in Q12
w(f"#define P5_LOG2_FLOOR_Q12 ({round(math.log2(1e-4) * 4096)})")
# blocks per Poly5 unit: attack = max(3 ms, a * 5 ms), release = max(30 ms, r * 20 ms)
w(f"#define P5_ATK_MIN_BLOCKS {round(0.001 * BR)}u")   # Poly5: 3 ms; here 1 ms, for a harder, percussive attack
w(f"#define P5_ATK_PER_UNIT_Q8 {round(0.005 * BR * 256)}u")
w(f"#define P5_REL_MIN_BLOCKS {round(0.03 * BR)}u")
w(f"#define P5_REL_PER_UNIT_Q8 {round(0.02 * BR * 256)}u")
# peak: vol/100 * vel/127 * 0.72/sqrt(8), as Q15 per (vol * vel)
w(f"#define P5_PK_Q15 {round(0.72 / math.sqrt(8) / 100 / 127 * 32768 * 65536)}u   /* >> 16 */")
# cutoff: log2(cHz/20) = c/100 * log2(900), Q12 per unit
w(f"#define P5_CUT_PER_UNIT_Q12 {round(math.log2(900) / 100 * 4096)}u")
# pink noise (Poly5's getNoiseBuf): three one-poles, Q15
w(f"#define P5_PN_B0 {round(0.99765 * 32768)}")
w(f"#define P5_PN_B1 {round(0.96300 * 32768)}")
w(f"#define P5_PN_B2 {round(0.57000 * 32768)}")
w(f"#define P5_PN_G0 {round(0.099 * 32768)}")
w(f"#define P5_PN_G1 {round(0.299 * 32768)}")
w(f"#define P5_PN_G2 {round(1.907 * 32768)}")
w(f"#define P5_PN_GW {round(0.18 * 32768)}")
w(f"#define P5_PN_OUT {round(0.11 * 32768)}")
w("#endif")

Path(__file__).resolve().parent.parent.joinpath("firmware/gen/poly5_tables.h").write_text("\n".join(out) + "\n")
print("firmware/gen/poly5_tables.h written")
