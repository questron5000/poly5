"""The POLY5 video manual, chapter by chapter. Each runs on the firmware from power-on (patch F01, octave 0)."""
from manual import Chapter

CHAPTERS = []


def chapter(*a):
    c = Chapter(*a)
    CHAPTERS.append(c)
    return c


# 1 ---------------------------------------------------------------------------------------------------------------
c = chapter(1, "welcome", "Meet the five synths", "POLY5 is five synths in one. Each note you play goes to the next one in turn: that's round robin.")
c.cap("Switch on, and the five synths spring up: one for each letter of POLY5.").wait(2600)
c.cap("This is the home screen. Each shape is one synth, with its own colour and number.").wait(4200)
c.cap("The shape is the synth's wave: cube = square, pyramid = triangle, ramp = saw, globe = sine, diamond = FM.").wait(4800)
c.cap("Play a key. POLY5 starts in ROUND ROBIN: each note goes to the next synth.", "Five synths, five different sounds, one after the other.")
c.notes("A3 C4 E4 G4 A4 G4 E4 C4 A3 C4", step=520, gate=0.85)
c.wait(600)
c.cap("The amber bar under a number marks the synth that plays next.")
c.notes("E4 - E4 - E4 - E4 - E4", step=420, gate=0.8)
c.wait(400)
c.cap("A shape fills with light while its synth sounds, then drains as the note fades.")
c.notes("A4 - - E4 - - C4", step=420, gate=0.9)
c.wait(1400)
c.cap("Play a chord and its notes are dealt across the synths: every chord is a little ensemble.")
c.chord("A3 C4 E4 G4", 3200, roll=90, after=1200)
c.chord("F3 A3 C4 E4", 3200, roll=90, after=1500)
c.cap("Top left: POLY5. Top right: the play mode. Bottom: the patch you're on.", "Next: random, the key to everything.").wait(4200)
c.end()

# 2 ---------------------------------------------------------------------------------------------------------------
c = chapter(2, "random", "Random: the key to everything", "Who plays each note, what each synth sounds like, the order of an arpeggio: POLY5 leaves them to chance, and you keep what you love.")
c.wait(1500)
c.cap("POLY5 is built around chance. Three things can be random: who plays each note, what each synth sounds like, and the order of an arpeggio.").wait(5200)
c.cap("First, who plays. Hold ARP for the RANDOM play mode: each note jumps to a random synth, never the same one twice in a row.")
c.wait(1200).hold("ARP", 800, after=800)
c.notes("A3 C4 E4 G4 A4 G4 E4 C4", step=420).wait(600)
c.cap("Start the sequence with PLAY. The same six notes, but every pass lands on different synths, so it never plays the same way twice.")
c.tap("PLAY", after=7500)
c.cap("Second, the sounds. Press GLO and all five synths get a brand new sound, while the music keeps going.", "Keep pressing until something makes you smile.")
c.wait(1000)
for _ in range(4):
    c.tap("GLO", after=3600)
c.cap("Love four of them but not the fifth? Open that synth's page (here SEL, synth 2) and press GLO there: only that synth changes.")
c.wait(800).tap("SEL", after=1200)
c.tap("GLO", after=3000).tap("GLO", after=3000)
c.cap("Give it some breath: on a synth's page, PRESETS adds noise. Chance and noise are POLY5's two secret weapons.")
c.turn("PRESETS", 22, step=70, after=3500)
c.tap("SEL", after=1500)
c.cap("Third, the order. Tap ARP until it says RANDOM and hold a chord: random notes, from random synths.", "Stop the sequence first: the arpeggiator plays what you hold.")
c.tap("PLAY", after=1200)
for _ in range(4):
    c.tap("ARP", after=350)
c.wait(400).chord("A3 C4 E4 G4", 6500, after=600)
for _ in range(4):
    c.tap("ARP", after=250)
c.cap("Found something good? SAVE, SAVE keeps it (chapter 11). Random finds it; you decide what stays.").wait(4500)
c.end()

